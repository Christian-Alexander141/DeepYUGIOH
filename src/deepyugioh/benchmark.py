"""Benchmark: the existing generator (tiers 1-4) against AIDE and the hybrid tier 7.

Every variant gets the same card subset, the same search limits, the same
opponent boards and the same budget (number of searches), and writes into
its own fresh databases - the real Database 1 is never touched. Measured per
variant (proposal section 13):

    unique validated combos, combos per search, wall/CPU time per combo, RAM,
    candidates generated by AIDE, hypothesis status, duplicate candidates,
    combos only one variant found, share of not interpretable effects,
    and combo quality: card count, multi-card share, benefits, wins

A higher number of candidates alone proves nothing; what counts is how many
*new* validated combos a variant finds for the same budget.
"""

from __future__ import annotations

import hashlib
import json
import resource
import shutil
import time
from collections import Counter
from dataclasses import asdict, dataclass, field, replace
from functools import cached_property
from pathlib import Path

from deepyugioh.cards.graph import CardGraph
from deepyugioh.cards.references import constants, setcode_matches

DEFAULT_ARCHETYPES = (
    "SET_JUNK", "SET_SYNCHRON", "SET_LIGHTSWORN", "SET_SIX_SAMURAI", "SET_DRAGONMAID", "SET_SHADDOLL",
    "SET_TRAPTRIX", "SET_OGDOADIC", "SET_MATHMECH", "SET_SALAMANGREAT",
)
DEFAULT_STAPLES = (
    "Foolish Burial", "Monster Reborn", "Reinforcement of the Army", "One for One", "Dark Grepher", "Mathematician",
    "Sangan", "Doppelwarrior", "Tuningware", "Glow-Up Bulb", "Quick Launch", "Allure of Darkness", "Terraforming",
    "Instant Fusion", "Polymerization", "Gold Sarcophagus", "Card Destruction", "Armageddon Knight", "Junk Converter",
    "Marauding Captain", "Pot of Greed", "Upstart Goblin",
)
VARIANTS = {"baseline": [1, 2, 3, 4], "hybrid": [7], "aide": [5, 6]}


class SubsetGraph(CardGraph):
    """The interaction graph restricted to a card subset (helpers/enablers stay global)."""

    def __init__(self, base: CardGraph, codes):
        super().__init__(base.path)
        self.base = base
        self.subset = frozenset(codes)

    @cached_property
    def profiles(self):
        return {c: p for c, p in self.base.profiles.items() if c in self.subset}

    def interactions(self):
        return [i for i in self.base.interactions() if i.source in self.subset and i.target in self.subset]

    @cached_property
    def enablers(self):
        return self.base.enablers

    def version(self) -> str:
        digest = hashlib.sha256(json.dumps(sorted(self.subset)).encode()).hexdigest()[:12]
        return f"{self.base.version()}+subset:{digest}"

    def meta(self) -> dict:
        return {}

    def build(self):
        raise RuntimeError("a subset graph is read-only")


def subset_codes(graph: CardGraph, pool, archetypes=DEFAULT_ARCHETYPES, staples=DEFAULT_STAPLES) -> set[int]:
    consts = constants()
    out = set()
    for name in archetypes:
        sc = consts.get(name)
        if sc is None:
            raise KeyError(f"unknown archetype constant {name}")
        out.update(c for c, p in graph.profiles.items() if setcode_matches(p.setcodes, sc))
    for name in staples:
        code = pool.resolve(name).code
        if code in graph.profiles:
            out.add(code)
    return out


@dataclass
class BenchmarkSettings:
    budget: int = 400                     # searches per variant (budget_kind "searches") or seconds ("seconds")
    budget_kind: str = "searches"
    workers: int = 4
    max_nodes: int = 1500
    time_limit: float = 60.0
    max_cards: int = 5
    archetypes: tuple[str, ...] = DEFAULT_ARCHETYPES
    staples: tuple[str, ...] = DEFAULT_STAPLES
    variants: tuple[str, ...] = ("baseline", "hybrid", "aide")
    candidate_overrides: dict = field(default_factory=dict)   # e.g. {"aide_neighbors": 15}


def _usage():
    s, c = resource.getrusage(resource.RUSAGE_SELF), resource.getrusage(resource.RUSAGE_CHILDREN)
    return s.ru_utime + s.ru_stime + c.ru_utime + c.ru_stime, max(s.ru_maxrss, c.ru_maxrss)


def run_benchmark(settings: BenchmarkSettings, out_dir: Path, log=print) -> dict:
    from deepyugioh import settings as local_settings
    from deepyugioh.cards.signatures import SignatureStore
    from deepyugioh.cards.store import CardStore
    from deepyugioh.contracts.effects import summarize
    from deepyugioh.generator import ComboGenerator, JobStore
    from deepyugioh.generator.aide.hypotheses import HypothesisStore
    from deepyugioh.repository.combo_db import ComboRepository

    out_dir.mkdir(parents=True, exist_ok=True)
    pool = CardStore()
    base_graph = CardGraph()
    if base_graph.version() == "unbuilt":
        raise FileNotFoundError("interaction graph missing - run `deepyugioh import-cards`")
    codes = subset_codes(base_graph, pool, settings.archetypes, settings.staples)
    graph = SubsetGraph(base_graph, codes)
    knowledge = SignatureStore()
    cfg = local_settings.generator_config()
    cfg = cfg.with_(
        limits=replace(cfg.limits, max_nodes=settings.max_nodes, time_limit=settings.time_limit, max_cards=settings.max_cards),
        candidates=replace(cfg.candidates, **settings.candidate_overrides),
        workers=settings.workers,
    )
    cfg.check()
    sig_stats = summarize(s for c in sorted(codes) for s in knowledge.signatures(c))
    log(f"subset: {len(codes)} cards, {len(graph.starters())} starters; effects {sig_stats}")

    results = {}
    for name in settings.variants:
        tiers = VARIANTS[name]
        work = out_dir / name
        if work.exists():
            shutil.rmtree(work)
        work.mkdir()
        repo = ComboRepository(work / "combos.sqlite")
        state = JobStore(work / "generator.sqlite")
        hyp = HypothesisStore(work / "aide.sqlite")
        gen = ComboGenerator(pool, repo, cfg, graph=graph, state=state, pool_factory=CardStore, knowledge=knowledge,
                             hypotheses=hyp, aide_codes=codes)
        log(f"[{name}] tiers {tiers}, budget {settings.budget} {settings.budget_kind} ...")
        cpu0, _ = _usage()
        t0 = time.perf_counter()
        if settings.budget_kind == "seconds":
            report = gen.run(tiers=tiers, time_budget=float(settings.budget))
        else:
            report = gen.run(tiers=tiers, max_jobs=settings.budget)
        wall = time.perf_counter() - t0
        cpu1, rss = _usage()
        hyp_counts = hyp.update_status(state.jobs_for, repo.cards_for_runs)
        res = _variant_result(name, tiers, report, repo, state, hyp, gen, wall, cpu1 - cpu0, rss)
        res["hypotheses"] = dict(hyp_counts)
        results[name] = res
        log(f"[{name}] {res['searches']} searches, {res['unique_combos']} unique combos in {wall:.0f}s")
        repo.close()
        state.close()
        hyp.close()

    comparison = _compare(results)
    summary = {
        "settings": {**asdict(settings), "subset_cards": len(codes), "starters": len(graph.starters()),
                     "limits": asdict(cfg.limits), "opponent_boards": list(cfg.candidates.opponent_boards),
                     "candidates": asdict(cfg.candidates)},
        "effects": sig_stats,
        "variants": {k: {x: y for x, y in v.items() if x != "signatures"} for k, v in results.items()},
        "comparison": comparison,
        "created": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    (out_dir / "benchmark.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False))
    (out_dir / "benchmark.md").write_text(markdown(summary))
    return summary


def _variant_result(name, tiers, report, repo, state, hyp, gen, wall, cpu, rss) -> dict:
    combos = list(repo.iter_combos())
    sizes = Counter(c.card_count for c in combos)
    positives = Counter(p for c in combos for p in c.positive)
    aide_setups = set()
    for row in hyp.list(limit=10**9):
        aide_setups.update(row["setups"])
    first_from_aide, found_by_aide = set(), set()
    if aide_setups:
        for sig, cand in repo.db.execute("SELECT c.signature, r.candidate FROM combos c JOIN runs r ON r.id = c.first_run"):
            if cand in aide_setups:
                first_from_aide.add(sig)
        for sig, cand in repo.db.execute(
                "SELECT c.signature, r.candidate FROM combo_runs cr JOIN combos c ON c.id = cr.combo_id"
                " JOIN runs r ON r.id = cr.run_id"):
            if cand in aide_setups:
                found_by_aide.add(sig)
    aide_searches = sum(1 for (cand,) in repo.db.execute("SELECT candidate FROM runs") if cand in aide_setups)
    src = gen.source
    duplicates = getattr(src, "duplicates", 0) + (getattr(src.aide, "duplicates", 0) if "aide" in src.__dict__ else 0)
    n = len(combos)
    return {
        "tiers": tiers,
        "searches": report.jobs,
        "complete": report.complete,
        "incomplete": report.incomplete,
        "errors": report.errors,
        "skipped_known": report.skipped,
        "duplicates_dropped": duplicates,
        "aide_searches": aide_searches,
        "aide_plans": len(hyp.list(limit=10**9)),
        "unique_combos": n,
        "combos_per_search": round(n / report.jobs, 3) if report.jobs else 0.0,
        "searches_with_combo": repo.db.execute("SELECT COUNT(*) FROM runs WHERE combos_found > 0").fetchone()[0],
        "first_found_by_aide": len(first_from_aide),
        "found_in_aide_searches": len(found_by_aide),
        "wall_s": round(wall, 1),
        "cpu_s": round(cpu, 1),
        "cpu_s_per_combo": round(cpu / n, 3) if n else None,
        "combos_per_cpu_minute": round(60 * n / cpu, 2) if cpu else None,
        "max_rss_mb": round(rss / 1024, 1),
        "quality": {
            "mean_cards": round(sum(c.card_count for c in combos) / n, 2) if n else 0.0,
            "share_3plus_cards": round(sum(v for k, v in sizes.items() if k >= 3) / n, 3) if n else 0.0,
            "by_card_count": dict(sorted(sizes.items())),
            "mean_benefits": round(sum(len(c.positive) for c in combos) / n, 2) if n else 0.0,
            "by_benefit": dict(positives.most_common()),
            "wins": positives.get("wins", 0),
            "validated_share": round(sum(c.validated for c in combos) / n, 3) if n else 1.0,
        },
        "signatures": sorted(c.signature for c in combos),
    }


def _compare(results: dict) -> dict:
    out = {}
    if "baseline" in results:
        base = set(results["baseline"]["signatures"])
        for name, r in results.items():
            if name == "baseline":
                continue
            other = set(r["signatures"])
            out[name] = {
                "only_here": len(other - base),
                "only_in_baseline": len(base - other),
                "in_both": len(base & other),
                "unique_combos_vs_baseline": len(other) - len(base),
            }
        if "aide" in results and "hybrid" in results:
            aide = set(results["aide"]["signatures"])
            union = base | set(results["hybrid"]["signatures"])
            out["aide_beyond_baseline_and_hybrid"] = len(aide - union)
    return out


def markdown(summary: dict) -> str:
    v = summary["variants"]
    names = list(v)
    rows = [
        ("Suchen", "searches"), ("davon AIDE-Aufbauten", "aide_searches"), ("einzigartige validierte Combos", "unique_combos"),
        ("Combos pro Suche", "combos_per_search"), ("Suchen mit mindestens einer Combo", "searches_with_combo"),
        ("zuerst in AIDE-Suchen gefunden", "first_found_by_aide"), ("AIDE-Pläne (Hypothesen)", "aide_plans"),
        ("doppelte Kandidaten verworfen", "duplicates_dropped"), ("unvollständige Suchen", "incomplete"),
        ("Fehler", "errors"), ("Laufzeit (s)", "wall_s"), ("CPU (s)", "cpu_s"), ("CPU pro Combo (s)", "cpu_s_per_combo"),
        ("max. RAM (MB)", "max_rss_mb"), ("Combos pro CPU-Minute", "combos_per_cpu_minute"),
    ]
    q_rows = [("Karten pro Combo (Mittel)", "mean_cards"), ("Anteil Combos mit 3+ Karten", "share_3plus_cards"),
              ("Nutzenarten pro Combo (Mittel)", "mean_benefits"), ("Combos mit Sieg", "wins"),
              ("Anteil validiert", "validated_share")]
    s = summary["settings"]
    lines = [
        f"# Benchmark {summary['created']}", "",
        f"Kartenmenge: {s['subset_cards']} Karten ({s['starters']} Startkarten), Budget {s['budget']} "
        f"{'Sekunden' if s['budget_kind'] == 'seconds' else 'Suchen'} pro Variante, "
        f"{s['workers']} Prozesse, Grenzen: {s['limits']['max_nodes']} Knoten, {s['limits']['time_limit']:g}s, "
        f"{s['limits']['min_cards']}-{s['limits']['max_cards']} Karten, Gegner {', '.join(s['opponent_boards'])}.", "",
        "| Kennzahl | " + " | ".join(names) + " |", "|---|" + "---|" * len(names),
    ]
    for label, key in rows:
        lines.append(f"| {label} | " + " | ".join(str(v[n].get(key, "-")) for n in names) + " |")
    lines += ["", "**Qualität der Combos**", "", "| Kennzahl | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for label, key in q_rows:
        lines.append(f"| {label} | " + " | ".join(str(v[n]["quality"].get(key, "-")) for n in names) + " |")
    lines += ["", "**Vergleich mit baseline (Stufen 1-4)**", ""]
    for name, c in summary["comparison"].items():
        if isinstance(c, dict):
            lines.append(f"- {name}: {c['only_here']} Combos nur hier, {c['only_in_baseline']} nur in baseline, "
                         f"{c['in_both']} in beiden ({c['unique_combos_vs_baseline']:+d} gegenüber baseline)")
        else:
            lines.append(f"- {name}: {c}")
    hyp = {n: v[n].get("hypotheses", {}) for n in names}
    lines += ["", "**Status der AIDE-Hypothesen**", ""]
    for n in names:
        if hyp[n]:
            lines.append(f"- {n}: " + ", ".join(f"{k} {c}" for k, c in sorted(hyp[n].items())))
    e = summary["effects"]
    lines += ["", f"Effekte der Kartenmenge: {e['usable']} nutzbar, {e['unknown_share']:.0%} mit unbekannten Teilen "
              f"({e['unknown_share_without_conditions']:.0%} ohne Bedingungen), mittlere Sicherheit {e['mean_confidence']:.2f}.", ""]
    return "\n".join(lines)
